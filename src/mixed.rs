//! Section VII A: stabilizer mixed states.
//!
//! A mixed state with an r-generator stabilizer M_1..M_r has density matrix
//! ρ = 2^{−n} ∏ (I + M_i). The tableau keeps 2n rows:
//!
//! ```text
//! rows 0 .. r        destabilizers of the r generators
//! rows r .. n        logical X̄_1 .. X̄_{n−r}
//! rows n .. n+r      stabilizer generators
//! rows n+r .. 2n     logical Z̄_1 .. Z̄_{n−r}
//! row  2n            scratch
//! ```
//!
//! Row i and row ī (= i ± n) anticommute; every other pair commutes. Gates
//! act on every row exactly as in Section III. Measurement has three cases.

use crate::circuit::Gate;
use crate::error::{index_err, value_err, Error, Result};
use crate::gf2::symplectic_completion;
use crate::pauli::PauliString;
use crate::rng::Rng;
use crate::rows::Rows;
use crate::tableau::{canonical_generators, MeasureResult, Tableau};
use std::fmt;

#[derive(Clone, Debug)]
pub struct MixedTableau {
    n: usize,
    rank: usize,
    rows: Rows,
}

impl MixedTableau {
    /// |0⟩ on qubits 0..r and the maximally mixed state on qubits r..n, with
    /// X̄_i = X_{i+r} and Z̄_i = Z_{i+r}.
    ///
    /// (The paper says "0 on the first n − r qubits", which conflicts with its
    /// own X̄_i = X_{i+r}; this follows the formulas: r generators fix r
    /// qubits.)
    pub fn new(n: usize, rank: usize) -> Result<Self> {
        if n == 0 {
            return value_err("n must be positive");
        }
        if rank > n {
            return value_err(format!("rank {rank} exceeds {n} qubits"));
        }
        let mut rows = Rows::new(n, 2 * n + 1);
        for q in 0..n {
            rows.set_x(q, q, true);
            rows.set_z(n + q, q, true);
        }
        Ok(MixedTableau { n, rank, rows })
    }

    /// A pure state viewed as a mixed state of rank n.
    pub fn from_pure(t: &Tableau) -> Self {
        let n = t.num_qubits();
        MixedTableau {
            n,
            rank: n,
            rows: t.rows().clone(),
        }
    }

    /// The mixed state whose stabilizer group is generated by `stabs`
    /// (independent, commuting, Hermitian; at most n of them).
    pub fn from_stabilizers(n: usize, stabs: &[PauliString]) -> Result<Self> {
        if n == 0 {
            return value_err("n must be positive");
        }
        let r = stabs.len();
        let (d, xb, zb) = symplectic_completion(n, stabs)?;
        let mut t = MixedTableau::new(n, r)?;
        for i in 0..r {
            t.rows.set_row_pauli(i, &d[i]);
            t.rows.set_row_pauli(n + i, &stabs[i]);
        }
        for k in 0..n - r {
            t.rows.set_row_pauli(r + k, &xb[k]);
            t.rows.set_row_pauli(n + r + k, &zb[k]);
        }
        Ok(t)
    }

    pub fn num_qubits(&self) -> usize {
        self.n
    }

    /// The number r of stabilizer generators. r = n means a pure state.
    pub fn rank(&self) -> usize {
        self.rank
    }

    pub fn stabilizers(&self) -> Vec<PauliString> {
        (self.n..self.n + self.rank)
            .map(|i| self.rows.row_pauli(i))
            .collect()
    }

    /// All 2n rows in tableau order (destabilizers, X̄, stabilizers, Z̄).
    pub fn all_rows(&self) -> Vec<PauliString> {
        (0..2 * self.n).map(|i| self.rows.row_pauli(i)).collect()
    }

    pub fn canonical_stabilizers(&self) -> Vec<PauliString> {
        canonical_generators(self.n, self.stabilizers())
    }

    fn check_qubit(&self, q: usize) -> Result<()> {
        if q >= self.n {
            return index_err(format!("qubit {q} out of range [0, {})", self.n));
        }
        Ok(())
    }

    pub fn cnot(&mut self, a: usize, b: usize) -> Result<()> {
        self.check_qubit(a)?;
        self.check_qubit(b)?;
        if a == b {
            return value_err("CNOT control and target must differ");
        }
        self.rows.cnot(a, b);
        Ok(())
    }

    pub fn h(&mut self, a: usize) -> Result<()> {
        self.check_qubit(a)?;
        self.rows.h(a);
        Ok(())
    }

    pub fn p(&mut self, a: usize) -> Result<()> {
        self.check_qubit(a)?;
        self.rows.p(a);
        Ok(())
    }

    pub fn apply_unitary(&mut self, gate: &Gate) -> Result<()> {
        match *gate {
            Gate::Cnot(a, b) => self.cnot(a, b),
            Gate::H(a) => self.h(a),
            Gate::P(a) => self.p(a),
            Gate::Measure(_) => value_err("expected a unitary gate"),
        }
    }

    fn rowsum(&mut self, h: usize, i: usize) -> Result<()> {
        self.rows.rowsum(h, i).map_err(|_| {
            Error::Value(
                "mixed tableau invariants are broken (rowsum on anticommuting rows)".into(),
            )
        })
    }

    /// Case II: Z_a is ± a product of stabilizer generators; returns its sign.
    fn determinate_outcome(&mut self, a: usize) -> Result<bool> {
        let s = 2 * self.n;
        self.rows.zero_row(s);
        for i in 0..self.rank {
            if self.rows.x(i, a) {
                self.rowsum(s, self.n + i)?;
            }
        }
        Ok(self.rows.r(s))
    }

    /// `Some(bit)` if measuring `a` has a determinate outcome (Case II).
    pub fn peek(&mut self, a: usize) -> Result<Option<bool>> {
        self.check_qubit(a)?;
        let (n, r) = (self.n, self.rank);
        let any_x = |rng: std::ops::Range<usize>, rows: &Rows| rng.clone().any(|i| rows.x(i, a));
        if any_x(n..n + r, &self.rows) || any_x(r..n, &self.rows) || any_x(n + r..2 * n, &self.rows)
        {
            return Ok(None);
        }
        self.determinate_outcome(a).map(Some)
    }

    fn measure_with(&mut self, a: usize, choose: impl FnOnce() -> bool) -> Result<MeasureResult> {
        self.check_qubit(a)?;
        let (n, r) = (self.n, self.rank);

        // Case I: Z_a anticommutes with a stabilizer generator.
        if let Some(p) = (n..n + r).find(|&p| self.rows.x(p, a)) {
            for i in 0..2 * n {
                if i != p && i != p - n && self.rows.x(i, a) {
                    self.rowsum(i, p)?;
                }
            }
            self.rows.copy_row(p - n, p);
            self.rows.zero_row(p);
            let outcome = choose();
            self.rows.set_r(p, outcome);
            self.rows.set_z(p, a, true);
            return Ok(MeasureResult {
                outcome,
                deterministic: false,
            });
        }

        // Case III: Z_a commutes with the stabilizer but not with some
        // logical operator, so it is not in the stabilizer.
        let logical = (r..n).chain(n + r..2 * n).find(|&m| self.rows.x(m, a));
        let Some(mut m) = logical else {
            // Case II: Z_a is in the stabilizer.
            return Ok(MeasureResult {
                outcome: self.determinate_outcome(a)?,
                deterministic: true,
            });
        };
        // Put the anticommuting logical in the Z̄ half by swapping X̄_k with
        // Z̄_k. The pair stays a pair, and the final swaps below then keep
        // rows i and i + n partners (the paper's literal swaps undo
        // themselves when m = r).
        if m < n {
            self.rows.swap_rows(m, m + n);
            m += n;
        }
        let mbar = m - n;
        for i in 0..2 * n {
            if i != m && i != mbar && self.rows.x(i, a) {
                self.rowsum(i, m)?;
            }
        }
        self.rows.copy_row(mbar, m);
        self.rows.zero_row(m);
        let outcome = choose();
        self.rows.set_r(m, outcome);
        self.rows.set_z(m, a, true);
        // The new generator goes to row n + r, its destabilizer to row r.
        self.rows.swap_rows(m, n + r);
        self.rows.swap_rows(mbar, r);
        self.rank += 1;
        Ok(MeasureResult {
            outcome,
            deterministic: false,
        })
    }

    pub fn measure(&mut self, a: usize, rng: &mut Rng) -> Result<MeasureResult> {
        self.measure_with(a, || rng.bit())
    }

    /// Post-selected measurement; fails if `outcome` has probability 0.
    pub fn measure_forced(&mut self, a: usize, outcome: bool) -> Result<MeasureResult> {
        if let Some(det) = self.peek(a)? {
            if det != outcome {
                return value_err(format!(
                    "qubit {a} is determinately {}, cannot force {}",
                    det as u8, outcome as u8
                ));
            }
        }
        self.measure_with(a, || outcome)
    }

    /// Discards (traces out) qubit `a`, leaving n − 1 qubits; higher qubits
    /// shift down by one.
    ///
    /// The paper's recipe: reduce the stabilizer so that at most one
    /// generator has an X on `a` and at most one has a Z, drop those, and
    /// keep the rest. The paper omits the O(n²) bookkeeping for X̄ and Z̄
    /// ("rather involved"), so this rebuilds them by symplectic completion,
    /// in O(n³).
    pub fn discard(&mut self, a: usize) -> Result<()> {
        self.check_qubit(a)?;
        if self.n == 1 {
            return value_err("cannot discard the only qubit");
        }
        let mut gens = self.stabilizers();
        for use_x in [true, false] {
            let bit = |p: &PauliString| {
                let (x, z) = p.get(a);
                if use_x {
                    x
                } else {
                    z
                }
            };
            if let Some(i) = gens.iter().position(bit) {
                let pivot = gens.remove(i);
                for g in gens.iter_mut() {
                    if bit(g) {
                        *g = pivot.mul(g);
                    }
                }
            }
        }
        let reduced: Vec<PauliString> = gens.iter().map(|g| g.remove_qubit(a)).collect();
        *self = MixedTableau::from_stabilizers(self.n - 1, &reduced)?;
        Ok(())
    }

    /// Rows i and j anticommute iff j = ī.
    pub fn check_invariants(&self) -> Result<()> {
        let n = self.n;
        for i in 0..2 * n {
            for j in i + 1..2 * n {
                let want = j == i + n;
                if self.rows.anticommute(i, j) != want {
                    return value_err(format!(
                        "rows {i} and {j} should {}",
                        if want { "anticommute" } else { "commute" }
                    ));
                }
            }
        }
        Ok(())
    }
}

impl fmt::Display for MixedTableau {
    /// The stabilizer generators, one per line (`(maximally mixed)` if none).
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let s = self.stabilizers();
        if s.is_empty() {
            return f.write_str("(maximally mixed)");
        }
        let lines: Vec<String> = s.iter().map(|p| p.to_string()).collect();
        f.write_str(&lines.join("\n"))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn case_three_purifies() {
        // One maximally mixed qubit: the first measurement is random and
        // adds a generator; the second is determinate.
        let mut rng = Rng::seed_from_u64(1);
        let mut t = MixedTableau::new(1, 0).unwrap();
        let a = t.measure(0, &mut rng).unwrap();
        assert!(!a.deterministic);
        assert_eq!(t.rank(), 1);
        let b = t.measure(0, &mut rng).unwrap();
        assert!(b.deterministic);
        assert_eq!(a.outcome, b.outcome);
        t.check_invariants().unwrap();
    }

    #[test]
    fn case_three_with_x_bar_row() {
        // Rank 0 on 2 qubits: the first logical row with x_m1 = 1 is X̄_1 = X_1,
        // in the X̄ region, which exercises the pre-swap.
        let mut t = MixedTableau::new(2, 0).unwrap();
        t.measure_forced(1, true).unwrap();
        t.check_invariants().unwrap();
        assert_eq!(t.stabilizers()[0].to_string(), "-IZ");
    }

    #[test]
    fn invariants_survive_random_operations() {
        let mut rng = Rng::seed_from_u64(77);
        for n in 1..7 {
            for r in 0..=n {
                let mut t = MixedTableau::new(n, r).unwrap();
                for _ in 0..30 {
                    let a = rng.below(n);
                    match rng.below(4) {
                        0 if n > 1 => {
                            let mut b = rng.below(n - 1);
                            if b >= a {
                                b += 1;
                            }
                            t.cnot(a, b).unwrap();
                        }
                        1 => t.h(a).unwrap(),
                        2 => t.p(a).unwrap(),
                        _ => {
                            t.measure(a, &mut rng).unwrap();
                        }
                    }
                    t.check_invariants().unwrap();
                }
            }
        }
    }

    #[test]
    fn discard_bell_pair_gives_mixed_qubit() {
        let mut t = Tableau::new(2);
        t.h(0).unwrap();
        t.cnot(0, 1).unwrap();
        let mut m = MixedTableau::from_pure(&t);
        m.discard(1).unwrap();
        assert_eq!((m.num_qubits(), m.rank()), (1, 0));
        m.check_invariants().unwrap();
    }
}
